from __future__ import annotations
from pydantic import BaseModel, Field


class AiHealthInsight(BaseModel):
    repo: str
    provider: str
    model: str
    health_summary: str = Field(description="Short executive summary of overall repo health")
    strengths: list[str] = Field(default_factory=list)
    risks: list[str] = Field(default_factory=list)
    recommendations: list[str] = Field(default_factory=list)
    readme_assessment: str | None = Field(default=None, description="What the README suggests about maturity, onboarding, and maintenance")
    community_signals: str | None = Field(default=None, description="Interpretation of issues/PRs/activity patterns")
    disclaimer: str = Field(default="Generated by an AI model from public GitHub data; verify before decisions.")
